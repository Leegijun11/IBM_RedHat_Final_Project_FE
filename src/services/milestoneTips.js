export function getAgeInMonths(birthStr) {
  if (!birthStr) return null;
  const birth = new Date(birthStr);
  const now = new Date();
  let months = (now.getFullYear() - birth.getFullYear()) * 12 + (now.getMonth() - birth.getMonth());
  if (now.getDate() < birth.getDate()) months -= 1;
  return months;
}

function getNearestBrackets(ageMonths, count = 2) {
  if (ageMonths === null) return [];
  return [...MONTH_BRACKETS]
    .sort((a, b) => Math.abs(a - ageMonths) - Math.abs(b - ageMonths))
    .slice(0, count);
}

export function getTipPool(ageMonths) {
  const nearBrackets = getNearestBrackets(ageMonths);
  const relevantIds = MILESTONES
    .filter((m) => nearBrackets.includes(m.m_months))
    .map((m) => m.m_id);

  const tips = relevantIds.map((id) => MILESTONE_TIPS[id]).filter(Boolean);

  return tips.length > 0 ? tips : GENERIC_TIPS;
}