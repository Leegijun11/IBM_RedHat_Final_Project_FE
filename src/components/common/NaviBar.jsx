function NaviBar() {
    const navigate = useNavigate();
    const location = useLocation();

    const isActive = (path) => path && location.pathname.startsWith(path);

    const navItems = [
        { label: "홈",       path: "/home",   icon: <HomeIcon /> },
        { label: "기록",     path: "/diary",  icon: <DiaryIcon /> },
        { label: "책",       path: "/ebook",  icon: <BookIcon /> },
        { label: "커뮤니티",  path: "/community",   icon: <CommunityIcon /> },
        { label: "설정",     path: "/mypage", icon: <SettingsIcon /> },
    ];

    return (
        <div className="navibar-wrap">
            {navItems.map((item) => (
                <div
                    key={item.label}
                    className={`navibar-item ${isActive(item.path) ? "active" : ""}`}
                    onClick={() => item.path && navigate(item.path)}
                >
                    <span className="nav-icon">{item.icon}</span>
                    <span className="nav-label">{item.label}</span>
                </div>
            ))}
        </div>
    );
}

export default NaviBar;